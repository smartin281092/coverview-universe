export function baseQuestion(id: string): RecommendationQuestion {
  const definition = recommendationQuestions.find((value) => value.id === id);
  if (!definition) throw new Error("Unknown recommendation question");
  return {
    ...definition,
    reason: "requested",
    sensitivity: {
      examinedAlternatives: 0,
      changesLeader: false,
      changesCost: false,
      changesCompatibility: false,
    },
    subjectId: null,
  };
}
export function usageQuestion(id: string, title: string): RecommendationQuestion {
  return {
    ...baseQuestion("lifestyle"),
    id: `usage:${id}`,
    title,
    help: "Seul un usage déjà prévu ou habituel peut produire une valeur réalisable, si les conditions sont confirmées.",
    multiple: false,
    subjectId: id,
    options: options(
      ["current", "Je l’utilise déjà."],
      ["planned", "Je prévois de l’utiliser cette année."],
      ["interest", "Cela m’intéresse, sans usage prévu."],
      ["none", "Je ne l’utiliserais probablement pas."],
      ["unknown", "Je ne sais pas.", true],
    ),
  };
}
