import { useBlocker } from "@tanstack/react-router";
import { useWalletProfileScope } from "../profile/use-wallet-profile-scope";
import { useEffect, useRef, useState } from "react";
import { useMutation, useQuery } from "@tanstack/react-query";
import { useForm } from "react-hook-form";
import { useTranslation } from "react-i18next";
import { ArrowDown, ArrowUp, Camera, FileText, Plus, Trash2 } from "lucide-react";
import {
  Button,
  Label,
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@coverview/ui";
import type { IdentityMe } from "@coverview/api-client";
import type { DocumentRecord } from "@coverview/contracts";
import { api } from "../../api";
import { DocumentFailure } from "./DocumentFailure";
import { DocumentProgress } from "./DocumentProgress";
import { DocumentLoadingMessage } from "./DocumentLoadingMessage";
import { DocumentCamera } from "./DocumentCamera";
import { DocumentSelectionPreview, type SelectedDocumentFile } from "./DocumentSelectionPreview";
import {
  DocumentPreparationError,
  maximumDocumentBytes,
  maximumDocumentPhotos,
  photoTypes,
  prepareDocumentFile,
} from "./document-upload-file";
import { numberFormat } from "../../number-format";

export function DocumentUpload({
  identity,
  pending,
  onDone,
  portalContainer,
  onBusyChange,
}: {
  identity: IdentityMe;
  pending?: DocumentRecord;
  onDone: (document: DocumentRecord) => void;
  portalContainer: HTMLDivElement | null;
  onBusyChange?: (busy: boolean) => void;
}) {
  const { t, i18n } = useTranslation("documents");
  const { scope, profileId } = useWalletProfileScope();
  const [targetProfile, setTargetProfile] = useState(profileId ?? "detect");
  const profiles = useQuery({
    queryKey: ["private", identity.user.id, identity.session.id, "managed-profiles"],
    queryFn: ({ signal }) => api.profiles({ signal }),
    enabled: !pending && scope === "all",
    gcTime: 0,
    staleTime: 0,
    retry: false,
  });
  const [files, setFiles] = useState<SelectedDocumentFile[]>([]);
  const [selectionError, setSelectionError] = useState<string>();
  const [previewId, setPreviewId] = useState<string>();
  const [camera, setCamera] = useState(false);
  const [step, setStep] = useState<"preparing" | "uploading">("preparing");
  const fileInput = useRef<HTMLInputElement>(null);
  const cameraInput = useRef<HTMLInputElement>(null);
  const urls = useRef(new Map<string, string>());
  const prepared = useRef<File | undefined>(undefined);
  const operation = useRef({ key: crypto.randomUUID(), id: pending?.id });
  const completed = useRef(false);
  const controller = useRef(new AbortController());
  useEffect(() => {
    const active = new AbortController();
    controller.current = active;
    const ownedUrls = urls.current;
    return () => {
      active.abort();
      for (const url of ownedUrls.values()) URL.revokeObjectURL(url);
      ownedUrls.clear();
    };
  }, []);
  const form = useForm({ defaultValues: { analysisRequested: true } });
  const mutation = useMutation({
    mutationKey: [
      "private",
      identity.user.id,
      identity.session.id,
      "document-upload",
      scope,
      targetProfile,
    ],
    gcTime: 0,
    mutationFn: async (analysisRequested: boolean) => {
      setStep("preparing");
      // A retry sends exactly the same generated bytes and command key.
      const file =
        prepared.current ??
        (await prepareDocumentFile(
          files.map((item) => item.file),
          t("capture.documentName"),
          controller.current.signal,
        ));
      prepared.current = file;
      const options = {
        csrfToken: identity.csrfToken,
        idempotencyKey: operation.current.key,
        signal: controller.current.signal,
      };
      if (!operation.current.id) {
        const digest = await crypto.subtle.digest("SHA-256", await file.arrayBuffer());
        const checksum = Array.from(new Uint8Array(digest), (byte) =>
          byte.toString(16).padStart(2, "0"),
        ).join("");
        const document = await api.createDocument(
          {
            name: file.name,
            ...(targetProfile === "detect"
              ? { detectProfile: true }
              : { profileId: targetProfile, detectProfile: false }),
            size: file.size,
            mime: file.type || "application/octet-stream",
            checksum,
            analysisRequested,
          },
          options,
        );
        operation.current.id = document.id;
      }
      setStep("uploading");
      return api.uploadDocument(operation.current.id, file, options);
    },
    onSuccess: (result) => {
      if (!controller.current.signal.aborted) {
        completed.current = true;
        onDone(result);
      }
    },
    retry: false,
  });
  useBlocker({
    shouldBlockFn: () => mutation.isPending && !completed.current,
    enableBeforeUnload: () => mutation.isPending && !completed.current,
  });
  useEffect(() => {
    onBusyChange?.(mutation.isPending);
  }, [mutation.isPending, onBusyChange]);
  const locked = mutation.isPending || (!pending && !!operation.current.id);
  function resetPreparation() {
    prepared.current = undefined;
    mutation.reset();
    setSelectionError(undefined);
    if (!operation.current.id) operation.current.key = crypto.randomUUID();
  }
  function receive(incoming: readonly File[]) {
    if (locked || !incoming.length) return false;
    const nextFiles = pending
      ? incoming.slice(0, 1)
      : [...files.map((item) => item.file), ...incoming];
    if (nextFiles.length > maximumDocumentPhotos) {
      setSelectionError(t("capture.photoCount"));
      return false;
    }
    if (
      nextFiles.some((file) => !file.size) ||
      nextFiles.reduce((sum, file) => sum + file.size, 0) > maximumDocumentBytes
    ) {
      setSelectionError(t("capture.size"));
      return false;
    }
    if (nextFiles.length > 1 && nextFiles.some((file) => !photoTypes.has(file.type))) {
      setSelectionError(t("capture.photosOnly"));
      return false;
    }
    if (pending) {
      for (const item of files) {
        URL.revokeObjectURL(item.url);
        urls.current.delete(item.id);
      }
    }
    const additions = (pending ? incoming.slice(0, 1) : incoming).map((file) => {
      const id = crypto.randomUUID();
      const url = URL.createObjectURL(file);
      urls.current.set(id, url);
      return { id, file, url };
    });
    setFiles(pending ? additions : [...files, ...additions]);
    resetPreparation();
    return true;
  }
  function remove(id: string) {
    if (locked) return;
    const url = urls.current.get(id);
    if (url) URL.revokeObjectURL(url);
    urls.current.delete(id);
    setFiles((current) => current.filter((file) => file.id !== id));
    if (previewId === id) setPreviewId(undefined);
    resetPreparation();
  }
  function move(index: number, direction: number) {
    if (locked) return;
    setFiles((current) => {
      const next = [...current];
      const item = next[index];
      const target = next[index + direction];
      if (item && target) {
        next[index] = target;
        next[index + direction] = item;
      }
      return next;
    });
    resetPreparation();
  }
  const canAddPhotos =
    !pending &&
    !locked &&
    files.length < maximumDocumentPhotos &&
    files.every((file) => photoTypes.has(file.file.type));
  return (
    <>
      <form
        className="space-y-6"
        onSubmit={(event) => {
          void form.handleSubmit((values) => mutation.mutate(values.analysisRequested))(event);
        }}
      >
        {pending && (
          <p className="text-sm text-muted-foreground">
            {t(pending.analysisRequested ? "resumeWithAi" : "resumeWithoutAi")}
          </p>
        )}
        <div className="space-y-3">
          <div className="flex flex-wrap gap-3">
            <Button
              type="button"
              variant="outline"
              className="min-h-11 flex-1"
              disabled={locked || (!pending && files.length > 0 && !canAddPhotos)}
              onClick={() => fileInput.current?.click()}
            >
              <Plus aria-hidden="true" />
              {t(pending ? "resumeFile" : files.length ? "capture.addFiles" : "chooseFile")}
            </Button>
            {!pending && (
              <Button
                type="button"
                variant="outline"
                className="min-h-11 flex-1"
                disabled={!canAddPhotos}
                onClick={() => setCamera(true)}
              >
                <Camera aria-hidden="true" />
                {t("capture.camera")}
              </Button>
            )}
          </div>
          <input
            ref={fileInput}
            type="file"
            className="hidden"
            multiple={!pending}
            disabled={locked}
            aria-label={t("chooseFile")}
            onChange={(event) => {
              receive(Array.from(event.currentTarget.files ?? []));
              event.currentTarget.value = "";
            }}
          />
          <input
            ref={cameraInput}
            type="file"
            accept="image/*"
            capture="environment"
            className="hidden"
            aria-label={t("capture.camera")}
            onChange={(event) => {
              receive(Array.from(event.currentTarget.files ?? []));
              event.currentTarget.value = "";
            }}
          />
          <p className="text-sm text-muted-foreground">
            {t(pending ? "resumeHelp" : "capture.help")}
          </p>
          {selectionError && (
            <p role="alert" className="text-sm text-destructive">
              {selectionError}
            </p>
          )}
        </div>
        {!!files.length && (
          <ol className="space-y-3" aria-label={t("capture.selection")}>
            {files.map((item, index) => (
              <li
                key={item.id}
                className="flex min-w-0 items-center gap-3 rounded-xl border border-border p-3"
              >
                <button
                  type="button"
                  className="group relative size-20 shrink-0 overflow-hidden rounded-lg border border-border bg-muted focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-ring"
                  onClick={() => setPreviewId(item.id)}
                  aria-label={t("capture.preview", { name: item.file.name })}
                >
                  {photoTypes.has(item.file.type) ? (
                    <img
                      src={item.url}
                      alt=""
                      className="size-full object-cover transition-transform group-hover:scale-105 motion-reduce:transition-none"
                    />
                  ) : (
                    <FileText className="mx-auto size-8 text-muted-foreground" aria-hidden="true" />
                  )}
                </button>
                <div className="min-w-0 flex-1">
                  <button
                    type="button"
                    className="max-w-full text-left text-sm font-medium underline-offset-4 hover:underline"
                    onClick={() => setPreviewId(item.id)}
                  >
                    <span className="break-all">{item.file.name}</span>
                  </button>
                  <p className="mt-1 text-xs text-muted-foreground">
                    {t("capture.fileMeta", {
                      index: index + 1,
                      size: numberFormat(i18n.language, {
                        maximumFractionDigits: 1,
                      }).format(item.file.size / 1024),
                    })}
                  </p>
                  <div className="mt-2 flex flex-wrap gap-1">
                    {files.length > 1 && (
                      <>
                        <Button
                          type="button"
                          size="icon"
                          variant="ghost"
                          className="min-h-11 min-w-11"
                          disabled={locked || index === 0}
                          aria-label={t("capture.moveUp", { name: item.file.name })}
                          onClick={() => move(index, -1)}
                        >
                          <ArrowUp className="size-4" aria-hidden="true" />
                        </Button>
                        <Button
                          type="button"
                          size="icon"
                          variant="ghost"
                          className="min-h-11 min-w-11"
                          disabled={locked || index === files.length - 1}
                          aria-label={t("capture.moveDown", { name: item.file.name })}
                          onClick={() => move(index, 1)}
                        >
                          <ArrowDown className="size-4" aria-hidden="true" />
                        </Button>
                      </>
                    )}
                    <Button
                      type="button"
                      size="icon"
                      variant="ghost"
                      className="min-h-11 min-w-11"
                      disabled={locked}
                      aria-label={t("capture.remove", { name: item.file.name })}
                      onClick={() => remove(item.id)}
                    >
                      <Trash2 className="size-4" aria-hidden="true" />
                    </Button>
                  </div>
                </div>
              </li>
            ))}
          </ol>
        )}
        {files.length > 1 && (
          <p className="text-sm text-muted-foreground">{t("capture.combineHelp")}</p>
        )}
        {!pending && scope === "all" && (
          <div className="space-y-2">
            <Label htmlFor="upload-profile">{t("uploadProfile.label")}</Label>
            <Select
              value={targetProfile}
              disabled={locked}
              onValueChange={(value) => {
                setTargetProfile(value);
                resetPreparation();
              }}
            >
              <SelectTrigger id="upload-profile" className="min-h-11 w-full">
                <SelectValue />
              </SelectTrigger>
              <SelectContent portalContainer={portalContainer}>
                <SelectItem value="detect">{t("uploadProfile.detect")}</SelectItem>
                {profiles.data?.profiles.map((profile) => (
                  <SelectItem key={profile.id} value={profile.id}>
                    {profile.displayName}
                  </SelectItem>
                ))}
              </SelectContent>
            </Select>
            <p className="text-sm text-muted-foreground">{t("uploadProfile.help")}</p>
            {profiles.isError && (
              <DocumentFailure error={profiles.error} onRetry={() => void profiles.refetch()} />
            )}
          </div>
        )}
        {!pending && (
          <label className="flex items-start gap-3 text-sm">
            <input
              type="checkbox"
              className="mt-1 size-4 shrink-0 accent-primary"
              disabled={locked}
              {...form.register("analysisRequested")}
            />
            <span>
              <span className="block font-medium">{t("analyzeChoice")}</span>
              <span className="mt-2 block text-muted-foreground">
                {t(targetProfile === "detect" ? "aiDisclosure" : "aiDisclosureAssigned")}
              </span>
            </span>
          </label>
        )}
        {mutation.isError &&
          (mutation.error instanceof DocumentPreparationError ? (
            <p role="alert" className="text-sm text-destructive">
              {t(`capture.${mutation.error.code}`)}
            </p>
          ) : (
            <DocumentFailure
              error={mutation.error}
              onRetry={() => mutation.mutate(form.getValues("analysisRequested"))}
            />
          ))}
        <Button
          className="min-h-11 w-full sm:w-auto"
          type="submit"
          disabled={!files.length || mutation.isPending}
        >
          {mutation.isPending ? t(step) : t(pending ? "resumeUpload" : "saveDocument")}
        </Button>
        {mutation.isPending && (
          <div className="space-y-3">
            <DocumentProgress label={t(step)} />
            <DocumentLoadingMessage key={step} phase={step} />
          </div>
        )}
      </form>
      {previewId && (
        <DocumentSelectionPreview
          files={files}
          selectedId={previewId}
          onSelect={setPreviewId}
          onClose={() => setPreviewId(undefined)}
          portalContainer={portalContainer}
        />
      )}
      {camera && (
        <DocumentCamera
          count={files.length}
          maximum={maximumDocumentPhotos}
          error={selectionError}
          onPhoto={(file) => receive([file])}
          onClose={() => setCamera(false)}
          portalContainer={portalContainer}
          onNativeCamera={() => {
            setCamera(false);
            cameraInput.current?.click();
          }}
        />
      )}
    </>
  );
}
