const values = z.object({
  languageCodes: z
    .array(professionalLanguageSchema)
    .max(20)
    .refine((items) => new Set(items).size === items.length),
  cantons: z
    .array(swissCantonSchema)
    .max(26)
    .refine((items) => new Set(items).size === items.length),
});
export const professionalPracticeInputSchema = values
  .extend({
    revision: z.number().int().nonnegative(),
    professionalRevision: z.number().int().positive(),
    confirmed: z.literal(true),
  })
  .strict();
export const professionalPracticeSummarySchema = values.extend({
  status: z.enum(["unset", "declared", "scope_changed"]),
  declaredAt: z.iso.datetime().nullable(),
});
const declaration = values.extend({
  revision: z.number().int().positive(),
  professionalRevision: z.number().int().positive(),
  declaredName: z.string(),
  declaredOrganization: z.string(),
  declaredAt: z.iso.datetime(),
  professionalScope: z.enum(["current", "changed"]),
});
export const professionalPracticeDossierSchema = z.object({
  userId: z.string(),
  name: z.string(),
  organization: z.string(),
  professionalRevision: z.number().int().positive(),
  canDeclare: z.boolean(),
  legacy: z.object({ languages: z.string(), regions: z.string() }),
  current: declaration.nullable(),
  history: z.array(declaration).max(20),
  nextBeforeRevision: z.number().int().positive().nullable(),
});
export type ProfessionalPracticeInput = z.infer<typeof professionalPracticeInputSchema>;
export type ProfessionalPracticeDossier = z.infer<typeof professionalPracticeDossierSchema>;
